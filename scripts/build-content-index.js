// ===== Content index =====
// Writes content/index.json: which content files each module actually has.
// Pages read it so they only ask for files that exist (no "404 not found" errors in the
// browser, and fewer requests, so pages load faster).
//
// Run it after adding or removing a content file:  node scripts/build-content-index.js
// The checker (scripts/check-content.js) tells you if the index is out of date.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const MODULES = path.join(ROOT, "content", "modules");
const FILES = ["topics.json", "flashcards.json", "questions.json", "resources.json"];

function buildIndex() {
  const modules = {};
  if (fs.existsSync(MODULES)) {
    for (const name of fs.readdirSync(MODULES).sort()) {
      const folder = path.join(MODULES, name);
      if (!fs.statSync(folder).isDirectory()) continue;
      const present = FILES.filter((file) => fs.existsSync(path.join(folder, file)));
      if (present.length) modules[name] = present;
    }
  }
  return JSON.stringify({ note: "Generated by scripts/build-content-index.js - do not edit by hand.", modules }, null, 2) + "\n";
}

if (require.main === module) {
  fs.writeFileSync(path.join(ROOT, "content", "index.json"), buildIndex());
  console.log("Wrote content/index.json");
}

module.exports = { buildIndex };
