// Render all app/browser icons from the user-selected Student Hub vector artwork.
// Run: node scripts/make-app-icons.js; then node scripts/make-social-image.js.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { chromium } = require("playwright");
const ROOT = path.join(__dirname, "..");
const source = fs.readFileSync(path.join(ROOT, "img/student-hub-mark.svg"), "utf8");
const geometry = source.match(/<g id="hub-mark">([\s\S]*)<\/g>/)[1];
const viewBox = source.match(/viewBox="([^"]+)"/)[1];
const fingerprint = crypto.createHash("sha1").update(source.replace(/\r\n/g, "\n")).digest("hex").slice(0, 8);
const icon = (maskable = false) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">
  <!-- Generated by scripts/make-app-icons.js from img/student-hub-mark.svg. -->
${maskable ? '  <rect width="64" height="64" fill="#0f2b5b"/>\n' : ''}  <g${maskable ? ' transform="translate(9.6 9.6) scale(.7)"' : ''}>${geometry}</g>
</svg>\n`;

(async () => {
  fs.writeFileSync(path.join(ROOT, "img/app-icon.svg"), icon());
  const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || (fs.existsSync("/usr/bin/chromium") ? "/usr/bin/chromium" : undefined);
  const browser = await chromium.launch({ ...(executablePath ? { executablePath } : {}), args: ["--no-sandbox"] });
  try {
    for (const [file, size, maskable] of [["app-icon-192.png", 192], ["app-icon-512.png", 512],
      ["app-icon-maskable-512.png", 512, true], ["apple-touch-icon.png", 180], ["favicon-32.png", 32]]) {
      const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
      await page.setContent(`<style>*{box-sizing:border-box}body{margin:0}svg{display:block;width:100vw;height:100vh}</style>${icon(maskable)}`);
      await page.screenshot({ path: path.join(ROOT, "img", file), omitBackground: true });
      await page.close();
      console.log(`Saved img/${file}`);
    }
  } finally { await browser.close(); }
  // Keep the social card's inline vector in sync; it also works from a local file.
  const template = path.join(ROOT, "scripts/social/template.html");
  const html = fs.readFileSync(template, "utf8");
  const markup = `<!-- hub-mark:start -->\n      <svg viewBox="${viewBox}" style="--hub-badge:#f7f5f1;--hub-pulse:#0f2b5b">${geometry}</svg>\n      <!-- hub-mark:end -->`;
  if (!html.includes("<!-- hub-mark:start -->")) throw new Error("Social template is missing the Student Hub mark slot.");
  fs.writeFileSync(template, html.replace(/<!-- hub-mark:start -->[\s\S]*?<!-- hub-mark:end -->/, markup));
  // Refresh the shared logo address so browser caches cannot retain an older mark.
  const nav = path.join(ROOT, "site-nav.js");
  const navScript = fs.readFileSync(nav, "utf8");
  const logoAddress = /img\/student-hub-mark\.svg(?:\?v=[0-9a-f]+)?#hub-mark/;
  if (!logoAddress.test(navScript)) throw new Error("Shared navigation is missing the Student Hub logo address.");
  fs.writeFileSync(nav, navScript.replace(logoAddress, `img/student-hub-mark.svg?v=${fingerprint}#hub-mark`));
})().catch((error) => { console.error(error); process.exitCode = 1; });
