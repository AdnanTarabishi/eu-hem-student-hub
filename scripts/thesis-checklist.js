// Writes docs/thesis-review-checklist.md: a short, numbered list for the student review of the
// classification (all "uncertain" and "medium" entries, plus a fixed sample of "high" ones).
// Usage: node scripts/thesis-checklist.js [sampleSize=10]
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8"));
global.readStorage = () => null;
global.simplify = (t) => String(t).normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
global.searchText = (t) => global.simplify(t).replace(/[^a-z0-9]+/g, " ").trim();
const TD = require(path.join(ROOT, "tracks-data.js"));
global.trackCourses = TD.trackCourses;
global.courseInfo = TD.courseInfo;
const EN = require(path.join(ROOT, "thesis-enrichment.js"));

const enrichment = read("content/thesis-enrichment.json");
const cohort = TD.tracksCohort(read("content/tracks.json"));
const ids = cohort.tracks.map((t) => t.id);
const themes = EN.topicThemes(enrichment, cohort);
const label = (id) => (themes.find((t) => t.id === id) || {}).label || id;
const abbr = (id) => cohort.tracks.find((t) => t.id === id).abbr;
const SAMPLE = Number(process.argv[2] || 10);

const pending = enrichment.records.filter((e) => e.status !== "reviewed");
const order = { uncertain: 0, medium: 1, high: 2 };
const checkAll = pending.filter((e) => e.confidence !== "high").sort((a, b) => order[a.confidence] - order[b.confidence]);
// Fixed sample (every n-th high entry by id), so the list is the same each time it is generated
const high = pending.filter((e) => e.confidence === "high").sort((a, b) => a.id.localeCompare(b.id));
const step = Math.max(1, Math.floor(high.length / SAMPLE));
const sample = high.filter((_, i) => i % step === 0).slice(0, SAMPLE);

const line = (e, n) => {
  const tracks = EN.trackRelevance(e, enrichment, ids).map((r) => abbr(r.trackId));
  const parts = [
    `**Themes:** ${e.themes.length ? e.themes.map(label).join(", ") : "none (unclassified)"}`,
    `**Tracks:** ${tracks.length ? tracks.join(", ") : "none"}`,
  ];
  if (e.statedMethods.length) parts.push(`**Method:** ${e.statedMethods.join(", ")}`);
  if (e.statedCountries.length) parts.push(`**Places:** ${e.statedCountries.join(", ")}`);
  return `${n}. [ ] ${e.title}  \n   ${parts.join(" · ")}${e.note ? `  \n   _Note: ${e.note}_` : ""}`;
};

let n = 0;
const out = [
  "# Thesis classification: review checklist",
  "",
  "Generated by `node scripts/thesis-checklist.js`. For each line, ask: do the themes fit the **title**? Is the",
  "track suggestion reasonable (or rightly \"none\")? Reply with the numbers to change, e.g. \"ok except 7: add",
  "policy; 12: no track\". Everything you confirm will be marked `reviewed`.",
  "",
  `## Check all (${checkAll.length}: uncertain first, then medium)`,
  "",
  ...checkAll.map((e) => line(e, ++n)),
  "",
  `## Spot-check sample (${sample.length} of ${high.length} high-confidence entries)`,
  "",
  "If these look right, the remaining high-confidence entries can be marked reviewed together.",
  "",
  ...sample.map((e) => line(e, ++n)),
  "",
];
fs.writeFileSync(path.join(ROOT, "docs", "thesis-review-checklist.md"), out.join("\n"));
console.log(`✔ Wrote docs/thesis-review-checklist.md: ${checkAll.length} to check + ${sample.length} sample (of ${high.length} high)`);
